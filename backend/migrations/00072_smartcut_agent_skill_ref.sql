- 智能剪辑没有导出成片时，下游生成会被拦下；导出用 render（给 smartcut_get 返回的 timelineId），或请用户在剪辑台里导出。
- 不修改用户的节点：要改用户建的或用户改过的节点时，在旁边新建一个，并在回复里说明它与原节点的关系。
- 不删除任何节点；确实需要删除时告诉用户，由用户自己删。
