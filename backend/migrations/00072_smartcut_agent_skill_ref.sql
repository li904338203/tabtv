- 视频 → 视频（默认操作 video2video）
- 音频 → 视频（默认操作 ref2video）
- 风格 → 图片（只作为修饰，叠加到目标节点的提示词）
- 特效 → 视频（只作为修饰，叠加到目标节点的提示词）
- 图片 → 3D 导演台（作导演台的全景背景或搭景参考图，不产生生成任务）
- 3D 导演台 → 图片（默认操作 img2img）
- 3D 导演台 → 视频（默认操作 ref2video）
- 视频 → 智能剪辑（作剪辑素材，连上即铺上时间线，不产生生成任务）
- 图片 → 智能剪辑（作剪辑素材，连上即铺上时间线，不产生生成任务）
- 音频 → 智能剪辑（作剪辑素材，连上即铺上时间线，不产生生成任务）
- 文本 → 智能剪辑（作剪辑素材，连上即铺上时间线，不产生生成任务）
- 脚本 → 智能剪辑（作剪辑素材，连上即铺上时间线，不产生生成任务）
- 组 → 智能剪辑（作剪辑素材，连上即铺上时间线，不产生生成任务）
- 智能剪辑 → 视频（默认操作 video2video）
- 智能剪辑 → 文本（默认操作 video2prompt）

不在上表里的连线一律不允许。视频节点的实际操作以所选模式为准（文生视频 / 图生视频 / 首尾帧 / 全能参考 / 视频生视频），表里的默认操作只是建议。

## 规则
- 连线有执行语义：连上的上游会作为下游生成的输入，顺序按连线的 order。不要用连线表达「来源」「参考过」这类关系。
- 文档节点不能连到任何节点上当输入；规划文档与产物的关系用画框表达。
