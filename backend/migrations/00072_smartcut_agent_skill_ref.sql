# 节点与连线

## 节点类型
- 文本（text）：能独立生成内容
- 图片（image）：能独立生成内容
- 视频（video）：能独立生成内容
- 音频（audio）：能独立生成内容
- 脚本（script）：组合 / 批量类节点，由对应流程创建，不要手工新建
- 组（group）：组合 / 批量类节点，由对应流程创建，不要手工新建
- 风格（style）：没有独立生成能力
- 特效（effect）：没有独立生成能力
- 文档（document）：没有独立生成能力
- 3D 导演台（director）：用 director_create 建、director_build 搭景；**不能截图**，搭完要提醒用户打开导演台截图；截图之后才能给下游当输入；连视频节点时建议用全能参考
- 智能剪辑（smartcut）：用 smartcut_create 建（可同时把素材节点按顺序连进来）、smartcut_plan 让 AI 按要求剪（免费，按用户限流）、smartcut_get 查看时间线与素材条；连进来的视频 / 图片 / 音频 / 文本按连线顺序自动铺上时间线（还没剪过时）；用户也可以在剪辑台里接着剪；导出成片用 render（给 smartcut_get 返回的 timelineId，导出免费）；导出成片之后才能给下游当输入
- 画框（frame）：纯视觉容器，只用来把相关节点框在一起；与「组」不同，没有批量执行与计费语义

