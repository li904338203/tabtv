// seedCameraMoves 写入运镜目录（视频节点的「运镜广场」，迁移 00064）。
//
// 这是产品配置不是用户数据：没有它，运镜广场是空的，视频节点的「运镜」按钮点开什么都选不了。
// 名称与顺序照对标产品的运镜广场；提示词写给视频模型看 —— 一句话说清「机位怎么动、画面会怎么变」，
// 不写画面内容（内容是用户的描述），也不写风格词（那是风格 / 特效的事）。
//
// ⚠️ 冲突时**跳过**而不是覆盖：运镜后台可以改（「风格与特效」页的运镜），重跑种子不能把运营改过的说法、
// 封面、上下线状态冲掉（同 Agent 技能的种子）。要改种子里的说法，新环境生效、已有环境在后台改。
// ⚠️ 提示词不下发前端（与风格、特效一样），由服务端在受理时拼进去（catalog/app.CameraPrompt）。
