const characterRefsAnchorRef = agentSkillPlaceholder + `

# 锚点派生与分档

## 为什么只有一个根
- 一致性来自「同一张锚点」，不来自「同一个模型」：锚点用一个模型、派生用另一个模型，只要都参考同一张锚点，通常衔接得上。
- 每张派生图只参考锚点（细节图可以加挂已确认的大头照），不参考别的派生图。坏一张就重出一张，不连锁。
- 冻结的只有三样：锚点、画风、角色设定的文字。任何一样变了，依赖它的图都算过期——只标记、不删除，旧图留在画布上供对比。

## 分档
| 档位 | 内容 | 什么时候出 |
|---|---|---|
| 1 | 正面全身（锚点），竖幅约 2:3 | 总是第一张 |
| 2（默认） | 正脸大头照（约 4:5）、90° 侧面（面朝画面右侧）、背面（2:3） | 默认出齐 |
| 3 | 细节特写（约 1:1，最多 8 张）：用户点名的、最能认出这个角色的地方；没有就用发饰、领口、袖口、鞋 | 有配饰或服装局部需要特写时 |
| 4 | 45° 大头照（面朝画面左侧） | 用户明确要时 |

- 只想先看长相时只出第 1 档，确认后再补。
- 只给正面全身当参考，服装和背影往往对，但脸容易走样；加一张大头照脸最接近——所以默认出齐第二档。
- 第三档的细节必须已经写在设定里：细节只决定拍哪些特写，不给角色添新东西。要加新配饰得先改设定，那会让整组过期。
- 脸上的特征（眼镜、痣、疤）不单独出细节图，大头照里已经看得清；单独出常会画成整张大头照。

## 设定怎么拆
- 身份：年龄（写具体岁数）、性别、年代、身份，写成一句能画出来的人物介绍。
- 脸：脸型、眼、眉、鼻、嘴、肤色、有辨识度的特征。不写「很美」，写「细长眼、高鼻梁、野生眉」。
- 服装拆上装与下装：大头照只能带上装，写了裤子和鞋模型会把镜头拉远去画它们。
- 小特征写成真实状态：旧疤写「愈合多年、细、平、略浅」，否则会画成新伤。
- 皮肤状态是角色属性不是画风：统一写「粗糙有瑕疵」会让年轻角色像生病。
- 描述里不写角色名、不写画风词，画风单独一句统一加，写进角色描述会和画风打架。
- 写实画风：写「真实照片、不是渲染」、有方向的主光加弱补光，纯白无缝背景；写光的效果不写光源（写「窗」会把窗户画进画面）。
- 动漫画风：写成「日式动画官方角色图」、干净线稿与赛璐璐上色。不要写「设定表」「三视图」「多视图」这类词——会让模型在一张图里画多个视图。

## 对接画布
- 锚点和派生图都是普通图片节点，可以连到视频节点当参考（如全能参考、图生视频），也可以连到脚本节点作角色参考图。
- 已有满意的单张角色图时，可以把它当锚点直接派生，不必重出；请用户确认这张图就是锚点。

借鉴来源：eternityspring/shuohao-skills（Apache-2.0）、freestylefly/awesome-gpt-image-2（MIT）
`

