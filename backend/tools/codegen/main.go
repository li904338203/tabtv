// Command codegen 由 api/errors.yaml 生成 Go 与 TypeScript 的错误码常量。
//
// ⚠️ 错误码只有一个来源（CD-15）。禁止在任何一端手写字面量；
// 生成物由 `make gen-check` 在 CI 里检出漂移。
//
// 同时校验两条不变式：
//  1. code 前 3 位必须等于 http（CD-01 —— 旧系统 HTTP 200 + 非零 code 的做法已废弃）；
//  2. code 与 name 均不得重复。
package main

import (
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"

	"gopkg.in/yaml.v3"
)

type catalog struct {
	Version int `yaml:"version"`
	Codes   []struct {
		Code      int    `yaml:"code"`
		Name      string `yaml:"name"`
		HTTP      int    `yaml:"http"`
		Message   string `yaml:"message"`
		Retryable bool   `yaml:"retryable"`
	} `yaml:"codes"`
	TaskErrorReasons []struct {
		Name    string `yaml:"name"`
		Message string `yaml:"message"`
	} `yaml:"task_error_reasons"`
}

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "codegen 失败:", err)
		os.Exit(1)
	}
}

func run() error {
	root, err := repoRoot()
	if err != nil {
		return err
	}
	raw, err := os.ReadFile(filepath.Join(root, "api", "errors.yaml"))
	if err != nil {
		return err
	}
	var c catalog
	if err := yaml.Unmarshal(raw, &c); err != nil {
		return fmt.Errorf("解析 errors.yaml: %w", err)
	}
	if err := validate(c); err != nil {
		return err
	}

	sort.Slice(c.Codes, func(i, j int) bool { return c.Codes[i].Code < c.Codes[j].Code })

	// 生成物必须自带格式，否则 make fmt-check 会一直红。
	formatted, err := format.Source([]byte(goSource(c)))
	if err != nil {
		return fmt.Errorf("格式化生成的 Go 代码失败: %w", err)
	}
	if err := write(filepath.Join(root, "backend", "internal", "transport", "errcode", "errcode_gen.go"), string(formatted)); err != nil {
		return err
	}
	if err := write(filepath.Join(root, "packages", "api-client", "src", "generated", "errors.ts"), tsSource(c)); err != nil {
		return err
	}
	fmt.Printf("错误码生成完成：%d 条\n", len(c.Codes))
	return nil
}

// validate 是本生成器存在的主要理由之一：约定必须被机器强制，
// 靠人记住"前三位要和 http 一致"迟早会漏。
func validate(c catalog) error {
	var errs []string
	seenCode := map[int]bool{}
	seenName := map[string]bool{}
	for _, e := range c.Codes {
		if seenCode[e.Code] {
			errs = append(errs, fmt.Sprintf("code %d 重复", e.Code))
		}
		seenCode[e.Code] = true
		if seenName[e.Name] {
			errs = append(errs, fmt.Sprintf("name %s 重复", e.Name))
		}
		seenName[e.Name] = true
		if e.Code == 0 {
			continue // 成功码不参与 HTTP 前缀校验
		}
		if prefix := strconv.Itoa(e.Code)[:3]; prefix != strconv.Itoa(e.HTTP) {
			errs = append(errs, fmt.Sprintf("code %d 的前 3 位 %s 与 http %d 不一致", e.Code, prefix, e.HTTP))
		}
	}
	if len(errs) > 0 {
		return fmt.Errorf("errors.yaml 校验未通过:\n  - %s", strings.Join(errs, "\n  - "))
	}
	return nil
}

func goSource(c catalog) string {
	var b strings.Builder
	b.WriteString("// Code generated by tools/codegen from api/errors.yaml. DO NOT EDIT.\n\n")
	b.WriteString("package errcode\n\n")
	b.WriteString("// Code 是业务错误码。前 3 位即 HTTP 状态码。\ntype Code int\n\nconst (\n")
	for _, e := range c.Codes {
		fmt.Fprintf(&b, "\t// %s %s\n\t%s Code = %d\n", e.Name, e.Message, goName(e.Name), e.Code)
	}
	b.WriteString(")\n\n")

	b.WriteString("var httpStatus = map[Code]int{\n")
	for _, e := range c.Codes {
		fmt.Fprintf(&b, "\t%s: %d,\n", goName(e.Name), e.HTTP)
	}
	b.WriteString("}\n\nvar messages = map[Code]string{\n")
	for _, e := range c.Codes {
		fmt.Fprintf(&b, "\t%s: %q,\n", goName(e.Name), e.Message)
	}
	b.WriteString("}\n\nvar names = map[Code]string{\n")
	for _, e := range c.Codes {
		fmt.Fprintf(&b, "\t%s: %q,\n", goName(e.Name), e.Name)
	}
	b.WriteString("}\n\nvar retryable = map[Code]bool{\n")
	for _, e := range c.Codes {
		if e.Retryable {
			fmt.Fprintf(&b, "\t%s: true,\n", goName(e.Name))
		}
	}
	b.WriteString("}\n\n")

	b.WriteString(`// HTTPStatus 返回该错误码对应的 HTTP 状态码。未知码按 500 处理。
func (c Code) HTTPStatus() int {
	if s, ok := httpStatus[c]; ok {
		return s
	}
	return 500
}

// Name 返回错误码的符号名，随响应体下发，让前端不必硬编码数字。
func (c Code) Name() string { return names[c] }

// Message 返回默认文案。调用方可覆盖为更具体的说明。
func (c Code) Message() string { return messages[c] }

// Retryable 表示客户端可否原样重试。用于前端自动重试与 Worker 重试分类。
func (c Code) Retryable() bool { return retryable[c] }
`)

	b.WriteString("\n// 任务终态原因。与 HTTP 错误码**不共用编号空间**：\n")
	b.WriteString("// 它们描述的是已受理任务的失败原因，不是请求结果。\nconst (\n")
	for _, r := range c.TaskErrorReasons {
		fmt.Fprintf(&b, "\t// %s\n\tReason%s = %q\n", r.Message, goName(r.Name), r.Name)
	}
	b.WriteString(")\n")
	return b.String()
}

func tsSource(c catalog) string {
	var b strings.Builder
	b.WriteString("// Code generated by tools/codegen from api/errors.yaml. DO NOT EDIT.\n\n")
	b.WriteString("export const ErrorCode = {\n")
	for _, e := range c.Codes {
		fmt.Fprintf(&b, "  /** %s */\n  %s: %d,\n", e.Message, e.Name, e.Code)
	}
	b.WriteString("} as const\n\n")
	b.WriteString("export type ErrorCode = (typeof ErrorCode)[keyof typeof ErrorCode]\n\n")

	b.WriteString("export const errorMessage: Record<number, string> = {\n")
	for _, e := range c.Codes {
		fmt.Fprintf(&b, "  %d: %q,\n", e.Code, e.Message)
	}
	b.WriteString("}\n\nexport const errorRetryable: Record<number, boolean> = {\n")
	for _, e := range c.Codes {
		fmt.Fprintf(&b, "  %d: %t,\n", e.Code, e.Retryable)
	}
	b.WriteString("}\n\n")
	b.WriteString("/** 任务终态原因，与 HTTP 错误码不共用编号空间。 */\nexport const TaskErrorReason = {\n")
	for _, r := range c.TaskErrorReasons {
		fmt.Fprintf(&b, "  /** %s */\n  %s: %q,\n", r.Message, r.Name, r.Name)
	}
	b.WriteString("} as const\n")
	return b.String()
}

func goName(s string) string {
	parts := strings.Split(strings.ToLower(s), "_")
	for i, p := range parts {
		if p == "" {
			continue
		}
		switch p {
		case "http", "json", "url", "id", "ok":
			parts[i] = strings.ToUpper(p)
		default:
			parts[i] = strings.ToUpper(p[:1]) + p[1:]
		}
	}
	return strings.Join(parts, "")
}

func write(path, content string) error {
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	return os.WriteFile(path, []byte(content), 0o644)
}

// repoRoot 从当前目录向上找含 api/errors.yaml 的目录。
// 不依赖 git：CI 的浅克隆与打包场景下 git 信息未必可用。
func repoRoot() (string, error) {
	dir, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for {
		if _, err := os.Stat(filepath.Join(dir, "api", "errors.yaml")); err == nil {
			return dir, nil
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			return "", fmt.Errorf("未找到仓库根（向上未见 api/errors.yaml）")
		}
		dir = parent
	}
}
